// ====================================================================================
// ФАЙЛ: RebarRecognizer.cs
// НАЗНАЧЕНИЕ: Автоматическое распознавание типа арматуры по геометрии полилинии
// ПЕРЕВЕДЕНО С: AutoLISP (POSEDIT.LSP) на C# для AutoCAD 2026 (.NET 8.0)
// ВЕРСИЯ ЯЗЫКА: C# 12 (collection expressions, pattern matching, и др.)
// ====================================================================================
// Этот класс содержит алгоритмы для автоматического распознавания формы арматуры
// на основе геометрии полилинии в AutoCAD.
//
// ПРИНЦИП РАБОТЫ:
//   1. Пользователь выбирает полилинию (Line, Polyline, Polyline2d)
//   2. Извлекаем все точки вершин полилинии
//   3. Определяем количество точек (2, 3, 4, 5, 6, 7 или 8)
//   4. В зависимости от количества точек вызываем соответствующую функцию распознавания
//   5. Функция нормализует точки (приводит к стандартному виду) и анализирует геометрию
//   6. По углам и длинам сегментов определяем тип арматуры (00, 11, 21, 41 и т.д.)
//   7. Возвращаем результат с типом и размерами (A, B, C, D, E, F, R)
//
// ТИПЫ АРМАТУРЫ (стандарт BS 8666):
//   - 00: Прямой стержень (2 точки)
//   - 11, 14, 15: Г-образная (3 точки)
//   - 21, 25, 41, 17: П, Z, Утка (4 точки)
//   - 30, 31, 38, 53: Хомуты, Стульчики (5 точек)
//   - 20, 39, 41: Сложные формы (6 точек)
//   - 49, 65: Специальные формы (7 точек)
//   - 48: Сложные формы (8 точек)
//   - 99: Не распознано (ошибка)
//
// C# 12 ОСОБЕННОСТИ:
//   - Pattern matching с is-expressions для проверки типов объектов
//   - Switch expressions для выбора функции распознавания
//   - Expression-bodied members для коротких методов
//   - Local functions для вспомогательных вычислений
// ====================================================================================

// Отключаем строгую проверку на null (пустые значения)
// В .NET 8 это включено по умолчанию, и без этой строки будет много предупреждений
#nullable disable

// Подключаем необходимые библиотеки
using System;                    // Базовые типы (Math, Convert, и т.д.)
using System.Collections.Generic; // Списки (List<T>)
using System.Linq;                // Дополнительные функции для работы с коллекциями
using Autodesk.AutoCAD.DatabaseServices; // Работа с базой данных AutoCAD (Entity, Transaction, ObjectId)
using Autodesk.AutoCAD.Geometry;         // Геометрия AutoCAD (Point3d, Vector3d, Tolerance)
using Autodesk.AutoCAD.ApplicationServices; // Приложение AutoCAD (Application для GetSystemVariable)

// Пространство имен должно совпадать с именем проекта!
namespace PoseEdit2026
{
    // ====================================================================================
    // КЛАСС: RebarResult
    // НАЗНАЧЕНИЕ: Хранит результат распознавания арматуры
    // ====================================================================================
    // Это как "коробка" для хранения всех данных, которые мы узнали об арматуре:
    // - Тип (00, 11, 21, 41 и т.д.)
    // - Размеры (A, B, C, D, E, F, R)
    // - Общая длина (Length)
    public class RebarResult
    {
        // Тип арматуры по стандарту BS 8666 (00 = прямая, 11 = Г-образная, 21 = П-образная и т.д.)
        // "99" = не распознано (ошибка)
        public string Type { get; set; } = "99";

        // Размеры арматуры (в миллиметрах, округленные до 10 мм)
        // A, B, C, D, E, F - это длины сегментов арматуры
        // R - радиус изгиба (если есть)
        public string A { get; set; } = "0";
        public string B { get; set; } = "0";
        public string C { get; set; } = "0";
        public string D { get; set; } = "0";
        public string E { get; set; } = "0";
        public string F { get; set; } = "0";
        public string R { get; set; } = "0";

        // Общая длина арматуры в формате "L=1200" (L = Length, длина)
        public string Length { get; set; } = "L=0";
    }

    // ====================================================================================
    // КЛАСС: RebarRecognizer
    // НАЗНАЧЕНИЕ: Главный класс для распознавания арматуры
    // ====================================================================================
    // "static" означает, что нам не нужно создавать объект этого класса.
    // Мы просто вызываем методы напрямую: RebarRecognizer.Recognize(...)
    public static class RebarRecognizer
    {
        // ====================================================================================
        // КОНСТАНТЫ (значения, которые не меняются)
        // ====================================================================================

        // SAYI = 10.0 - это шаг округления (из Lisp кода)
        // Все размеры округляются до 10 мм (например: 1234 мм -> 1230 мм, 1256 мм -> 1260 мм)
        // Это нужно, потому что в чертежах размеры могут быть неточными
        private const double SAYI = 10.0;

        // _scale - это масштабный коэффициент из системной переменной DIMLFAC
        // Если в AutoCAD установлен масштаб 1:100, то DIMLFAC = 100
        // Мы умножаем все размеры на этот коэффициент, чтобы получить реальные размеры
        private static double _scale = 1.0;

        // ====================================================================================
        // ГЛАВНАЯ ФУНКЦИЯ РАСПОЗНАВАНИЯ
        // ====================================================================================
        // Эта функция вызывается из PoseEditWindow.xaml.cs когда пользователь нажимает
        // кнопку "Determination" (Распознавание)
        //
        // ПАРАМЕТРЫ:
        //   entityId - это "паспорт" объекта в AutoCAD (полилинии, которую выбрал пользователь)
        //
        // ВОЗВРАЩАЕТ:
        //   RebarResult - объект с результатами распознавания (тип, размеры, длина)
        //
        // КАК ЭТО РАБОТАЕТ:
        //   1. Открываем объект из базы данных AutoCAD
        //   2. Извлекаем все точки из полилинии
        //   3. Считаем количество точек (2, 3, 4, 5, 6, 7 или 8)
        //   4. Вызываем соответствующую функцию распознавания
        //   5. Возвращаем результат
        public static RebarResult Recognize(ObjectId entityId)
        {
            // Создаем пустой результат (по умолчанию тип "99" = не распознано)
            RebarResult result = new RebarResult();

            // ТРАНЗАКЦИЯ - это способ безопасной работы с базой данных AutoCAD
            // Все изменения в AutoCAD должны происходить внутри транзакции
            // "using" автоматически закроет транзакцию в конце (даже если будет ошибка)
            using (Transaction tr = entityId.Database.TransactionManager.StartTransaction())
            {
                // Получаем объект из базы данных по его ID
                // "as Entity" означает: "попробуй преобразовать в Entity, если не получится - верни null"
                // Entity - это базовый класс для всех объектов AutoCAD (линии, полилинии, блоки и т.д.)
                Entity ent = tr.GetObject(entityId, OpenMode.ForRead) as Entity;

                // Если объект не найден или это не Entity - возвращаем пустой результат
                if (ent == null) return result;

                // ====================================================================================
                // ШАГ 1: ПОЛУЧАЕМ КОЭФФИЦИЕНТ ПЕРЕСЧЕТА ЕДИНИЦ (из настроек приложения)
                // ====================================================================================
                // Мы используем настройки из AppSettings.DrawingUnit (1000 для мм, 100 для см, 1 для м)
                // Коэффициент пересчета в миллиметры: 1000 / DrawingUnit
                _scale = 1000.0 / AppSettings.DrawingUnit;

                // ====================================================================================
                // ШАГ 2: ИЗВЛЕКАЕМ ТОЧКИ ИЗ ОБЪЕКТА
                // ====================================================================================
                // Вызываем вспомогательную функцию GetPointsFromEntity
                // Она извлекает все точки из полилинии или линии
                List<Point3d> pts = GetPointsFromEntity(ent);
                int npt = pts.Count; // Количество точек

                // Если точек меньше 2 - это не арматура (нужно минимум 2 точки для линии)
                if (npt < 2)
                {
                    result.Type = "99"; // Не распознано
                    tr.Commit();        // Сохраняем транзакцию (хотя ничего не изменили)
                    return result;
                }

                // ====================================================================================
                // ШАГ 3: ВЫЧИСЛЯЕМ ОБЩУЮ ДЛИНУ
                // ====================================================================================
                // Если объект - это кривая (Line, Polyline, Arc и т.д.)
                if (ent is Curve curve)
                {
                    // GetDistanceAtParameter - получает длину кривой до определенной точки
                    // EndParam - это параметр конечной точки (конец кривой)
                    // Таким образом мы получаем полную длину кривой
                    double lenParam = curve.GetDistanceAtParameter(curve.EndParam);

                    // Умножаем на масштаб и округляем до целых миллиметров
                    // Формат: "L=1200" (L = Length)
                    result.Length = "L=" + Round(lenParam * _scale).ToString("0");
                }

                // ====================================================================================
                // ШАГ 4: ВЫБИРАЕМ ФУНКЦИЮ РАСПОЗНАВАНИЯ ПО КОЛИЧЕСТВУ ТОЧЕК
                // ====================================================================================
                // В Lisp коде есть функции donati_tani_1, donati_tani_2, ... donati_tani_7
                // Каждая функция распознает арматуру с определенным количеством точек:
                //   - 2 точки  = прямая линия (тип 00)
                //   - 3 точки  = Г-образная (тип 11, 12, 14, 15)
                //   - 4 точки  = П, Z, Утка (тип 21, 25, 41 и др.)
                //   - 5 точек  = Хомуты, Стульчики (тип 30, 31, 38, 53)
                //   - 6 точек  = Сложные формы (тип 20, 39, 41)
                //   - 7 точек  = Специальные формы (тип 49, 65)
                //   - 8 точек  = Сложные формы (тип 48)
                switch (npt)
                {
                    case 2:
                        Recognize2Points(pts, result); // Прямая линия
                        break;
                    case 3:
                        Recognize3Points(pts, result); // Г-образная
                        break;
                    case 4:
                        Recognize4Points(pts, result); // П, Z, Утка
                        break;
                    case 5:
                        Recognize5Points(pts, result); // Хомуты, Стульчики
                        break;
                    case 6:
                        Recognize6Points(pts, result); // Сложные формы
                        break;
                    case 7:
                        Recognize7Points(pts, result); // Специальные формы
                        break;
                    case 8:
                        Recognize8Points(pts, result); // Сложные формы
                        break;
                    default:
                        // Если точек больше 8 или меньше 2 - не распознаем
                        result.Type = "99";
                        break;
                }

                // Сохраняем транзакцию (хотя мы только читали данные, не изменяли)
                tr.Commit();
            }

            // Возвращаем результат распознавания
            return result;
        }

        // ====================================================================================
        // ФУНКЦИЯ: RotatePoint (Поворот точки)
        // ====================================================================================
        // НАЗНАЧЕНИЕ: Поворачивает точку вокруг начала координат на заданный угол
        // ПЕРЕВЕДЕНО ИЗ: Lisp функция (defun koordinat_dondur ( point teta / ) ...)
        //
        // МАТЕМАТИКА:
        //   Когда мы поворачиваем точку на угол θ (тета), новые координаты вычисляются так:
        //   X' = X * cos(θ) - Y * sin(θ)  (новая координата X)
        //   Y' = X * sin(θ) + Y * cos(θ)  (новая координата Y)
        //   Z' = Z                        (координата Z не меняется)
        //
        // ЗАЧЕМ ЭТО НУЖНО:
        //   Чтобы привести арматуру к стандартному виду (повернуть так, чтобы было удобно анализировать)
        //   Например, поворачиваем так, чтобы один из сегментов был горизонтальным
        //
        // ПАРАМЕТРЫ:
        //   point - точка, которую нужно повернуть
        //   angle - угол поворота в радианах (не в градусах! 180° = π радиан)
        //
        // ВОЗВРАЩАЕТ:
        //   Новая точка с повернутыми координатами
        private static Point3d RotatePoint(Point3d point, double angle)
        {
            // Вычисляем косинус и синус угла один раз (чтобы не вычислять дважды)
            double cosA = Math.Cos(angle); // Косинус угла
            double sinA = Math.Sin(angle); // Синус угла

            // Вычисляем новые координаты по формулам поворота
            return new Point3d(
                point.X * cosA - point.Y * sinA, // Новая X координата
                point.X * sinA + point.Y * cosA, // Новая Y координата
                point.Z                          // Z координата не меняется
            );
        }

        // ====================================================================================
        // ФУНКЦИЯ: Normalize3Points (Нормализация 3 точек)
        // ====================================================================================
        // НАЗНАЧЕНИЕ: Приводит 3 точки к стандартному виду для анализа
        //
        // ЧТО ДЕЛАЕТ:
        //   1. Переносит все точки так, чтобы вторая точка была в начале координат (0, 0, 0)
        //   2. Поворачивает так, чтобы третий сегмент был горизонтальным (направлен вправо)
        //   3. Если нужно, отражает по оси X, чтобы первая точка была выше оси X
        //
        // ЗАЧЕМ ЭТО НУЖНО:
        //   Арматура может быть нарисована под любым углом и в любом месте чертежа
        //   Чтобы распознать её тип, нужно привести к стандартному виду
        //   Например: Г-образная арматура всегда будет выглядеть одинаково после нормализации
        //
        // ПАРАМЕТРЫ:
        //   pts - список из 3 точек (начало, угол, конец)
        //
        // ВОЗВРАЩАЕТ:
        //   Список из 3 нормализованных точек (вторая точка всегда в (0,0,0))
        private static List<Point3d> Normalize3Points(List<Point3d> pts)
        {
            // ШАГ 1: ПЕРЕНОСИМ ВСЕ ТОЧКИ В НАЧАЛО КООРДИНАТ
            // Берем вторую точку как "опорную" (она будет в центре координат)
            Point3d p2 = pts[1];

            // Создаем новый список нормализованных точек
            // Вычитаем координаты второй точки из всех точек (перенос в начало координат)
            List<Point3d> pp = new List<Point3d>
            {
                // Первая точка: вычитаем координаты второй точки
                new Point3d(pts[0].X - p2.X, pts[0].Y - p2.Y, 0),
                // Вторая точка: теперь она в начале координат (0, 0, 0)
                new Point3d(0, 0, 0),
                // Третья точка: вычитаем координаты второй точки
                new Point3d(pts[2].X - p2.X, pts[2].Y - p2.Y, 0)
            };

            // ШАГ 2: ВЫЧИСЛЯЕМ УГОЛ ПОВОРОТА
            // Нужно повернуть так, чтобы третий сегмент (от второй к третьей точке) был горизонтальным
            double teta; // Угол поворота в радианах

            // Если X координата третьей точки = 0 (вертикальная линия)
            if (Math.Abs(pp[2].X) < 0.0001) // 0.0001 - это очень маленькое число (почти ноль)
            {
                // Поворачиваем на 90 градусов (π/2 радиан)
                teta = Math.PI / 2.0;
            }
            else
            {
                // Вычисляем угол через арктангенс: atan(Y/X)
                // Минус нужен, чтобы повернуть в правильную сторону
                teta = -Math.Atan2(pp[2].Y, pp[2].X);
            }

            // ШАГ 3: ПОВОРАЧИВАЕМ ТОЧКИ
            // Поворачиваем первую и третью точку (вторая уже в центре, её не трогаем)
            pp[0] = RotatePoint(pp[0], teta);
            pp[2] = RotatePoint(pp[2], teta);

            // ШАГ 4: ЕСЛИ ТРЕТИЙ СЕГМЕНТ НАПРАВЛЕН ВЛЕВО - ПОВОРАЧИВАЕМ НА 180°
            // После поворота третий сегмент должен быть направлен вправо (X > 0)
            if (pp[2].X < 0)
            {
                // Поворачиваем все точки на 180° (π радиан)
                pp[0] = RotatePoint(pp[0], Math.PI);
                pp[2] = RotatePoint(pp[2], Math.PI);
            }

            // ШАГ 5: ЕСЛИ ПЕРВАЯ ТОЧКА НИЖЕ ОСИ X - ОТРАЖАЕМ ПО ОСИ X
            // После всех поворотов первая точка должна быть выше оси X (Y > 0)
            if (pp[0].Y < 0)
            {
                // Отражаем по оси X: меняем знак Y координаты
                pp[0] = new Point3d(pp[0].X, -pp[0].Y, 0);
            }

            // Возвращаем нормализованные точки
            return pp;
        }

        // ====================================================================================
        // ФУНКЦИЯ: Normalize4Points (Нормализация 4 точек)
        // ====================================================================================
        // НАЗНАЧЕНИЕ: Приводит 4 точки к стандартному виду для анализа
        // Аналогично Normalize3Points, но для 4 точек (П, Z, Утки)
        //
        // ПАРАМЕТРЫ:
        //   pts - список из 4 точек
        //
        // ВОЗВРАЩАЕТ:
        //   Список из 4 нормализованных точек
        private static List<Point3d> Normalize4Points(List<Point3d> pts)
        {
            // ШАГ 1: ПЕРЕНОСИМ В НАЧАЛО КООРДИНАТ (относительно второй точки)
            Point3d p2 = pts[1];
            List<Point3d> pp = new List<Point3d>
            {
                new Point3d(pts[0].X - p2.X, pts[0].Y - p2.Y, 0), // Первая точка
                new Point3d(0, 0, 0),                             // Вторая точка (центр)
                new Point3d(pts[2].X - p2.X, pts[2].Y - p2.Y, 0), // Третья точка
                new Point3d(pts[3].X - p2.X, pts[3].Y - p2.Y, 0)  // Четвертая точка
            };

            // ШАГ 2: ВЫЧИСЛЯЕМ УГОЛ ПОВОРОТА (чтобы третий сегмент был горизонтальным)
            double teta;
            if (Math.Abs(pp[2].X) < 0.0001)
                teta = Math.PI / 2.0; // Вертикальная линия
            else
                teta = -Math.Atan2(pp[2].Y, pp[2].X); // Вычисляем угол

            // ШАГ 3: ПОВОРАЧИВАЕМ ВСЕ ТОЧКИ (кроме второй, она в центре)
            pp[0] = RotatePoint(pp[0], teta);
            pp[2] = RotatePoint(pp[2], teta);
            pp[3] = RotatePoint(pp[3], teta);

            // ШАГ 4: ЕСЛИ ТРЕТИЙ СЕГМЕНТ НАПРАВЛЕН ВЛЕВО - ПОВОРАЧИВАЕМ НА 180°
            if (pp[2].X < 0)
            {
                pp[0] = RotatePoint(pp[0], Math.PI);
                pp[2] = RotatePoint(pp[2], Math.PI);
                pp[3] = RotatePoint(pp[3], Math.PI);
            }

            // ШАГ 5: ЕСЛИ ПЕРВАЯ ТОЧКА НИЖЕ ОСИ X - ОТРАЖАЕМ ПО ОСИ X
            if (pp[0].Y < 0)
            {
                // Отражаем первую и четвертую точки
                pp[0] = new Point3d(pp[0].X, -pp[0].Y, 0);
                pp[3] = new Point3d(pp[3].X, -pp[3].Y, 0);
            }

            return pp;
        }

        // ====================================================================================
        // ФУНКЦИЯ: Recognize2Points (Распознавание 2 точек)
        // ====================================================================================
        // НАЗНАЧЕНИЕ: Распознает прямую арматуру (2 точки = 1 сегмент)
        // ПЕРЕВЕДЕНО ИЗ: Lisp функция (defun donati_tani_1 (P1 P2 / ) ...)
        //
        // ТИП АРМАТУРЫ: 00 - Прямой стержень
        //
        // ПАРАМЕТРЫ:
        //   pts - список из 2 точек (начало и конец линии)
        //   res - объект результата, куда записываем данные
        //
        // КАК РАБОТАЕТ:
        //   1. Вычисляем расстояние между двумя точками (это длина арматуры)
        //   2. Умножаем на масштаб и округляем
        //   3. Записываем в результат: Type = "00", A = длина, остальное = "0"
        private static void Recognize2Points(List<Point3d> pts, RebarResult res)
        {
            // Вычисляем расстояние между первой и второй точкой
            // DistanceTo - это метод класса Point3d, который вычисляет расстояние до другой точки
            // Умножаем на масштаб (_scale) и округляем до 10 мм (функция Round)
            double boy1 = Round(pts[0].DistanceTo(pts[1]) * _scale);

            // Записываем результаты в объект res
            res.Type = "00";              // Тип: Прямой стержень
            res.A = boy1.ToString("0");   // Длина в поле A (формат "0" = без десятичных знаков)
            res.B = "0";                  // Остальные поля пустые
            res.C = "0";
            res.D = "0";
            res.E = "0";
            res.F = "0";
            res.R = "0";
        }

        // ====================================================================================
        // ФУНКЦИЯ: Recognize3Points (Распознавание 3 точек)
        // ====================================================================================
        // НАЗНАЧЕНИЕ: Распознает Г-образную арматуру (3 точки = 2 сегмента)
        // ПЕРЕВЕДЕНО ИЗ: Lisp функция (defun donati_tani_2 (P1 P2 P3 / ) ...)
        //
        // ТИПЫ АРМАТУРЫ:
        //   - 11: Г-образная с углом 90° (стандартная)
        //   - 14: Г-образная с острым углом (< 90°)
        //   - 15: Г-образная с тупым углом (> 90°, отгиб)
        //
        // ПАРАМЕТРЫ:
        //   pts - список из 3 точек
        //   res - объект результата
        //
        // КАК РАБОТАЕТ:
        //   1. Если первый сегмент длиннее второго - меняем порядок точек (для единообразия)
        //   2. Нормализуем точки (приводим к стандартному виду)
        //   3. Вычисляем угол между сегментами
        //   4. По углу определяем тип арматуры
        private static void Recognize3Points(List<Point3d> pts, RebarResult res)
        {
            // ШАГ 1: ПРОВЕРЯЕМ ДЛИНЫ СЕГМЕНТОВ
            // Если первый сегмент длиннее второго - меняем порядок точек
            // Это нужно для единообразия (в Lisp коде тоже так делается)
            double dist1 = pts[0].DistanceTo(pts[1]); // Длина первого сегмента
            double dist2 = pts[1].DistanceTo(pts[2]); // Длина второго сегмента

            if (dist1 > dist2)
            {
                // Меняем местами первую и третью точки
                var temp = pts[0];
                pts[0] = pts[2];
                pts[2] = temp;
            }

            // ШАГ 2: НОРМАЛИЗУЕМ ТОЧКИ
            // Приводим к стандартному виду (вторая точка в центре, третий сегмент горизонтальный)
            List<Point3d> pp = Normalize3Points(pts);

            // ШАГ 3: ВЫЧИСЛЯЕМ УГОЛ МЕЖДУ СЕГМЕНТАМИ
            // Atan2(Y, X) - это арктангенс, который учитывает знаки координат
            // Умножаем на 180/π, чтобы перевести из радиан в градусы
            // (int)(0.5 + ...) - это округление до ближайшего целого числа
            double alfa1 = (int)(0.5 + (Math.Atan2(pp[0].Y, pp[0].X) * 180.0 / Math.PI));

            // ШАГ 4: ВЫЧИСЛЯЕМ ДЛИНЫ СЕГМЕНТОВ
            // boy1 - длина первого сегмента (от второй точки к первой)
            // boy2 - длина второго сегмента (от второй точки к третьей)
            double boy1 = Round(_scale * pp[0].DistanceTo(pp[1]));
            double boy2 = Round(_scale * pp[1].DistanceTo(pp[2]));

            // ШАГ 5: ЗАПИСЫВАЕМ ДЛИНЫ В РЕЗУЛЬТАТ
            res.A = boy1.ToString("0");
            res.B = boy2.ToString("0");
            res.C = "0";
            res.D = "0";
            res.E = "0";
            res.F = "0";
            res.R = "0";

            // ШАГ 6: ОПРЕДЕЛЯЕМ ТИП ПО УГЛУ
            // alfa1 - это угол первого сегмента относительно горизонтали

            if (alfa1 < 90)
            {
                // ОСТРЫЙ УГОЛ (< 90°)
                // Вычисляем проекцию первого сегмента на вертикаль
                // Math.Sin(angle) - это синус угла (для вычисления вертикальной проекции)
                double boy3 = Round(_scale * Math.Abs(boy1 * Math.Sin(Math.Atan2(pp[0].Y, pp[0].X))));

                // Если длина равна проекции - это прямой угол (тип 11)
                // Иначе - острый угол (тип 14)
                if (Math.Abs(boy1 - boy3) < 0.1) // 0.1 мм - допуск на погрешность
                {
                    res.Type = "11"; // Г-образная 90°
                }
                else
                {
                    res.Type = "14"; // Г-образная с острым углом
                    res.C = boy3.ToString("0"); // Записываем проекцию в поле C
                }
            }
            else if (alfa1 == 90)
            {
                // ПРЯМОЙ УГОЛ (90°)
                res.Type = "11"; // Г-образная 90°
            }
            else // alfa1 > 90
            {
                // ТУПОЙ УГОЛ (> 90°)
                // Вычисляем проекцию
                double boy3 = Round(_scale * Math.Abs(boy1 * Math.Sin(Math.Atan2(pp[0].Y, pp[0].X))));

                if (Math.Abs(boy1 - boy3) < 0.1)
                {
                    res.Type = "11"; // Г-образная 90°
                }
                else
                {
                    res.Type = "15"; // Г-образная с тупым углом (отгиб)
                    res.C = boy3.ToString("0"); // Записываем проекцию в поле C
                }
            }
        }

        // ====================================================================================
        // ФУНКЦИЯ: Recognize4Points (Распознавание 4 точек)
        // ====================================================================================
        // НАЗНАЧЕНИЕ: Распознает П-образную, Z-образную и Утку (4 точки = 3 сегмента)
        // ПЕРЕВЕДЕНО ИЗ: Lisp функция (defun donati_tani_3 (P1 P2 P3 P4 / ) ...)
        //
        // ТИПЫ АРМАТУРЫ:
        //   - 21: П-образная (все углы 90°, повороты в одну сторону)
        //   - 25: Z-образная (углы 90°, повороты в разные стороны)
        //   - 41: Утка (Crank) - первый и последний сегмент параллельны
        //   - 17: Специальная форма
        //
        // ПАРАМЕТРЫ:
        //   pts - список из 4 точек
        //   res - объект результата
        //
        // КАК РАБОТАЕТ:
        //   1. Нормализуем точки
        //   2. Вычисляем длины всех сегментов
        //   3. Вычисляем углы между сегментами
        //   4. Проверяем на параллельность (Утка)
        //   5. По углам и направлениям поворотов определяем тип
        private static void Recognize4Points(List<Point3d> pts, RebarResult res)
        {
            // ШАГ 1: НОРМАЛИЗУЕМ ТОЧКИ
            List<Point3d> pp = Normalize4Points(pts);

            // ШАГ 2: ВЫЧИСЛЯЕМ ДЛИНЫ ВСЕХ СЕГМЕНТОВ
            double boy1 = Round(_scale * pp[0].DistanceTo(pp[1])); // Первый сегмент
            double boy2 = Round(_scale * pp[1].DistanceTo(pp[2])); // Второй сегмент (средний)
            double boy3 = Round(_scale * pp[2].DistanceTo(pp[3])); // Третий сегмент

            // ШАГ 3: ВЫЧИСЛЯЕМ УГЛЫ МЕЖДУ СЕГМЕНТАМИ
            // alfa1 - угол первого сегмента относительно горизонтали
            // alfa2 - угол третьего сегмента относительно горизонтали
            double alfa1 = (int)(0.5 + (Math.Atan2(pp[0].Y, pp[0].X) * 180.0 / Math.PI));
            double alfa2 = (int)(0.5 + (Math.Atan2(pp[3].Y - pp[2].Y, pp[3].X - pp[2].X) * 180.0 / Math.PI));
            if (alfa1 == 360) alfa1 = 0; // 360° = 0°
            if (alfa2 == 360) alfa2 = 0;

            // ШАГ 4: ЗАПИСЫВАЕМ ДЛИНЫ В РЕЗУЛЬТАТ
            res.A = boy1.ToString("0");
            res.B = boy2.ToString("0");
            res.C = boy3.ToString("0");
            res.D = "0";
            res.E = "0";
            res.F = "0";
            res.R = "0";

            // ШАГ 5: ПРОВЕРЯЕМ НА УТКУ (ТИП 41)
            // Утка - это когда первый и последний сегмент ПАРАЛЛЕЛЬНЫ
            // Создаем векторы из сегментов
            Vector3d v1 = new Vector3d(pp[0].X, pp[0].Y, 0); // Вектор первого сегмента
            Vector3d v3 = new Vector3d(pp[3].X - pp[2].X, pp[3].Y - pp[2].Y, 0); // Вектор третьего сегмента

            // IsParallelTo - проверяет, параллельны ли векторы
            // Tolerance(0.05, 0.05) - допуск на погрешность (5%)
            if (v1.IsParallelTo(v3, new Tolerance(0.05, 0.05)))
            {
                res.Type = "41"; // Утка (Crank)
                return; // Выходим из функции, дальше не проверяем
            }

            // ШАГ 6: ОПРЕДЕЛЯЕМ ТИП ПО УГЛАМ
            if (alfa1 == 90 && alfa2 == 90)
            {
                // ОБА УГЛА 90° - это П или Z
                // Проверяем направление поворотов
                bool turn1 = GetTurnDirection(pp[0], pp[1], pp[2]); // Направление первого поворота
                bool turn2 = GetTurnDirection(pp[1], pp[2], pp[3]); // Направление второго поворота

                if (turn1 == turn2)
                    res.Type = "21"; // П-образная (повороты в одну сторону)
                else
                    res.Type = "25"; // Z-образная (повороты в разные стороны)
            }
            else if (alfa1 < 90 && alfa2 > 90 && alfa2 < 180)
            {
                // ПЕРВЫЙ УГОЛ ОСТРЫЙ, ВТОРОЙ ТУПОЙ
                // Вычисляем проекции сегментов
                double boy4 = Round(_scale * Math.Abs(boy1 * Math.Sin(Math.Atan2(pp[0].Y, pp[0].X))));
                double boy5 = Round(_scale * Math.Abs(boy3 * Math.Sin(Math.Atan2(pp[3].Y - pp[2].Y, pp[3].X - pp[2].X))));

                // Если проекции равны длинам - это П-образная
                if (Math.Abs(boy1 - boy4) < 0.1 && Math.Abs(boy3 - boy5) < 0.1)
                {
                    res.Type = "21"; // П-образная
                }
                else
                {
                    // Специальная форма (тип 17)
                    res.Type = "17";
                    res.D = boy5.ToString("0");
                    res.E = boy2.ToString("0");
                    res.A = boy1.ToString("0");
                    res.B = boy3.ToString("0");
                    res.C = boy4.ToString("0");
                }
            }
            else
            {
                // ДРУГИЕ СЛУЧАИ - не распознано
                res.Type = "99";
            }
        }

        // ====================================================================================
        // ФУНКЦИЯ: Recognize5Points (Распознавание 5 точек)
        // ====================================================================================
        // НАЗНАЧЕНИЕ: Распознает хомуты и стульчики (5 точек = 4 сегмента)
        // ПЕРЕВЕДЕНО ИЗ: Lisp функция (defun donati_tani_4 (P1 P2 P3 P4 P5 / ) ...)
        //
        // ТИПЫ АРМАТУРЫ:
        //   - 31: Хомут (квадрат, все углы 90°, все повороты в одну сторону)
        //   - 30: Специальная форма
        //   - 38: Стульчик (Chair)
        //   - 53: Специальная форма
        //
        // ПАРАМЕТРЫ:
        //   pts - список из 5 точек
        //   res - объект результата
        private static void Recognize5Points(List<Point3d> pts, RebarResult res)
        {
            // ШАГ 1: НОРМАЛИЗАЦИЯ ДЛЯ 5 ТОЧЕК
            // Переносим в начало координат относительно второй точки
            Point3d p2 = pts[1];
            List<Point3d> pp = new List<Point3d>();
            foreach (var pt in pts)
            {
                pp.Add(new Point3d(pt.X - p2.X, pt.Y - p2.Y, 0));
            }

            // ШАГ 2: ВЫЧИСЛЯЕМ УГОЛ ПОВОРОТА
            double teta;
            if (Math.Abs(pp[2].X) < 0.0001)
                teta = Math.PI / 2.0;
            else
                teta = -Math.Atan2(pp[2].Y, pp[2].X);

            // ШАГ 3: ПОВОРАЧИВАЕМ ВСЕ ТОЧКИ (кроме второй)
            for (int i = 0; i < pp.Count; i++)
            {
                if (i != 1) pp[i] = RotatePoint(pp[i], teta);
            }

            // ШАГ 4: ЕСЛИ ТРЕТИЙ СЕГМЕНТ НАПРАВЛЕН ВЛЕВО - ПОВОРАЧИВАЕМ НА 180°
            if (pp[2].X < 0)
            {
                for (int i = 0; i < pp.Count; i++)
                {
                    if (i != 1) pp[i] = RotatePoint(pp[i], Math.PI);
                }
            }

            // ШАГ 5: ЕСЛИ ПЕРВАЯ ТОЧКА НИЖЕ ОСИ X - ОТРАЖАЕМ
            if (pp[0].Y < 0)
            {
                pp[0] = new Point3d(pp[0].X, -pp[0].Y, 0);
                pp[3] = new Point3d(pp[3].X, -pp[3].Y, 0);
                pp[4] = new Point3d(pp[4].X, -pp[4].Y, 0);
            }

            // ШАГ 6: ВЫЧИСЛЯЕМ ДЛИНЫ ВСЕХ СЕГМЕНТОВ
            double boy1 = Round(_scale * pp[0].DistanceTo(pp[1]));
            double boy2 = Round(_scale * pp[1].DistanceTo(pp[2]));
            double boy3 = Round(_scale * pp[2].DistanceTo(pp[3]));
            double boy4 = Round(_scale * pp[3].DistanceTo(pp[4]));

            // ШАГ 7: ВЫЧИСЛЯЕМ УГЛЫ
            double alfa1 = (int)(0.5 + (Math.Atan2(pp[0].Y, pp[0].X) * 180.0 / Math.PI));
            double alfa2 = (int)(0.5 + (Math.Atan2(pp[3].Y - pp[2].Y, pp[3].X - pp[2].X) * 180.0 / Math.PI));
            double alfa3 = (int)(0.5 + (Math.Atan2(pp[4].Y - pp[3].Y, pp[4].X - pp[3].X) * 180.0 / Math.PI));
            if (alfa1 == 360) alfa1 = 0;
            if (alfa2 == 360) alfa2 = 0;
            if (alfa3 == 360) alfa3 = 0;

            // ШАГ 8: ЗАПИСЫВАЕМ ДЛИНЫ В РЕЗУЛЬТАТ
            res.A = boy1.ToString("0");
            res.B = boy2.ToString("0");
            res.C = boy3.ToString("0");
            res.D = boy4.ToString("0");
            res.E = "0";
            res.F = "0";
            res.R = "0";

            // ШАГ 9: ОПРЕДЕЛЯЕМ ТИП ПО УГЛАМ
            if (alfa1 == 90 && alfa2 == 90 && alfa3 == 180)
            {
                // ХОМУТ (квадрат) - все углы 90°, последний 180° (замыкается)
                res.Type = "31"; // Хомут
            }
            else if (alfa1 == 90 && alfa2 < 90 && alfa3 == 90)
            {
                // СПЕЦИАЛЬНАЯ ФОРМА (тип 30)
                res.Type = "30";
                res.A = boy4.ToString("0");
                res.B = boy3.ToString("0");
                res.C = boy2.ToString("0");
                res.D = Round(_scale * Math.Abs(boy3 * Math.Cos(Math.Atan2(pp[3].Y - pp[2].Y, pp[3].X - pp[2].X)))).ToString("0");
                res.E = boy1.ToString("0");
            }
            else
            {
                // НЕ РАСПОЗНАНО
                res.Type = "99";
            }
        }

        // ====================================================================================
        // ФУНКЦИЯ: Recognize6Points (Распознавание 6 точек)
        // ====================================================================================
        // НАЗНАЧЕНИЕ: Распознает сложные формы арматуры (6 точек = 5 сегментов)
        // ПЕРЕВЕДЕНО ИЗ: Lisp функция (defun donati_tani_5 (P1 P2 P3 P4 P5 P6 / ) ...)
        //
        // ТИПЫ АРМАТУРЫ:
        //   - 41: Утка (Crank) - первый и последний сегмент параллельны
        //   - 20: Специальная форма
        //   - 39: Специальная форма
        private static void Recognize6Points(List<Point3d> pts, RebarResult res)
        {
            // ШАГ 1: НОРМАЛИЗАЦИЯ (центр в третьей точке)
            Point3d p3 = pts[2];
            List<Point3d> pp = new List<Point3d>();
            foreach (var pt in pts)
