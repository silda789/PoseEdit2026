            double alfa1 = AngleDeg(AngleRad(pp[1], pp[0])); // angle(PP2,PP1)
            double alfa2 = AngleDeg(AngleRad(pp[2], pp[1])); // angle(PP3,PP2)
            double alfa3 = AngleDeg(AngleRad(pp[3], pp[2])); // angle(PP4,PP3)
            double alfa4 = AngleDeg(AngleRad(pp[4], pp[5])); // angle(PP5,PP6)
            double alfa5 = AngleDeg(AngleRad(pp[5], pp[6])); // angle(PP6,PP7)
            double alfa6 = AngleDeg(AngleRad(pp[6], pp[7])); // angle(PP7,PP8)

            res.R = "0";

            // ШАГ 5: ПОЛНЫЙ ПОРТ ВЕТВЛЕНИЯ ИЗ Lisp donati_tani_7 (POSEDIT.LSP, ~строки 1616-1714)
            double sin34 = Math.Abs(Math.Sin(AngleRad(pp[2], pp[3]))); // |Sin(angle PP3 PP4)|
            bool distOk = Math.Abs(Math.Floor(pp[0].DistanceTo(pp[1])) - Math.Floor(pp[2].DistanceTo(pp[3]) * sin34)) <= 1;

            if (alfa1 == 270 && alfa2 == 180 && alfa3 > 90 && alfa3 < 180 && alfa4 < 90 && alfa5 == 0 && alfa6 == 270
                && Eq(boy1, boy7) && Eq(boy3, boy5) && distOk)
            {
                Set(res, "48", boy2, boy3, boy4, boy1, boy6);
                res.F = "0";
            }
            else
            {
                res.Type = "99";
            }
        }

        // ====================================================================================
        // ВСПОМОГАТЕЛЬНЫЕ ФУНКЦИИ
        // ====================================================================================

        // ====================================================================================
        // ФУНКЦИЯ: GetPointsFromEntity (Извлечение точек из объекта)
        // ====================================================================================
        // НАЗНАЧЕНИЕ: Извлекает все точки из объекта AutoCAD (Line, Polyline, Polyline2d)
        //
        // ПАРАМЕТРЫ:
        //   ent - объект AutoCAD (Entity)
        //
        // ВОЗВРАЩАЕТ:
        //   Список точек (Point3d)
        //
        // КАК РАБОТАЕТ:
        //   - Если это Line - берем StartPoint и EndPoint
        //   - Если это Polyline - берем все вершины через GetPoint3dAt
        //   - Если это Polyline2d - берем вершины через коллекцию Vertex2d
        private static List<Point3d> GetPointsFromEntity(Entity ent)
        {
            // Создаем пустой список для точек
            List<Point3d> pts = new List<Point3d>();

            // ПРОВЕРЯЕМ ТИП ОБЪЕКТА И ИЗВЛЕКАЕМ ТОЧКИ

            if (ent is Line line)
            {
                // ЛИНИЯ - просто берем начальную и конечную точку
                pts.Add(line.StartPoint); // Начальная точка
                pts.Add(line.EndPoint);    // Конечная точка
            }
            else if (ent is Polyline poly)
            {
                // ПОЛИЛИНИЯ - берем все вершины
                // NumberOfVertices - количество вершин в полилинии
                for (int i = 0; i < poly.NumberOfVertices; i++)
                {
                    // GetPoint3dAt(i) - получает точку вершины по индексу
                    pts.Add(poly.GetPoint3dAt(i));
                }
            }
            else if (ent is Polyline2d poly2d)
            {
                // ПОЛИЛИНИЯ 2D - более сложный случай
                // Нужно открыть транзакцию, чтобы получить доступ к вершинам
                using (Transaction tr = ent.Database.TransactionManager.StartTransaction())
                {
                    // Пробегаемся по всем объектам в коллекции полилинии
                    foreach (ObjectId id in poly2d)
                    {
                        // Получаем вершину по её ID
                        Vertex2d vtx = tr.GetObject(id, OpenMode.ForRead) as Vertex2d;
                        if (vtx != null)
                        {
                            // Добавляем позицию вершины в список
                            pts.Add(vtx.Position);
                        }
                    }
                    tr.Commit();
                }
            }

            // Возвращаем список точек
            return pts;
        }

        // ====================================================================================
        // ФУНКЦИЯ: GetTurnDirection (Определение направления поворота)
        // ====================================================================================
        // НАЗНАЧЕНИЕ: Определяет, в какую сторону поворачивает арматура (влево или вправо)
        //
        // МАТЕМАТИКА:
        //   Используем векторное произведение (Cross Product)
        //   Если Z компонента > 0 - поворот влево
        //   Если Z компонента < 0 - поворот вправо
        //
        // ПАРАМЕТРЫ:
        //   p1, p2, p3 - три точки (начало сегмента, угол, конец сегмента)
        //
        // ВОЗВРАЩАЕТ:
        //   true = поворот влево, false = поворот вправо
        //
        // КАК ЭТО РАБОТАЕТ:
        //   1. Создаем два вектора: от p1 к p2 и от p2 к p3
        //   2. Вычисляем Z компоненту векторного произведения
        //   3. Если Z > 0 - поворот влево, иначе - вправо
        private static bool GetTurnDirection(Point3d p1, Point3d p2, Point3d p3)
        {
            // ВЕКТОР 1: от первой точки ко второй (входящий сегмент)
            double v1x = p2.X - p1.X; // X компонента вектора 1
            double v1y = p2.Y - p1.Y; // Y компонента вектора 1

            // ВЕКТОР 2: от второй точки к третьей (исходящий сегмент)
            double v2x = p3.X - p2.X; // X компонента вектора 2
            double v2y = p3.Y - p2.Y; // Y компонента вектора 2

            // ВЫЧИСЛЯЕМ Z КОМПОНЕНТУ ВЕКТОРНОГО ПРОИЗВЕДЕНИЯ
            // Формула: Z = X1 * Y2 - Y1 * X2
            // Это определяет, в какую сторону поворачивает арматура
            double crossZ = v1x * v2y - v1y * v2x;

            // Если Z > 0 - поворот влево (против часовой стрелки)
            // Если Z < 0 - поворот вправо (по часовой стрелке)
            return crossZ > 0; // true = Лево, false = Право
        }

        // ====================================================================================
        // ФУНКЦИЯ: Round (Округление)
        // ====================================================================================
        // НАЗНАЧЕНИЕ: Округляет значение до ближайшего кратного 10 мм
        // ПЕРЕВЕДЕНО ИЗ: Lisp выражение (float (* (fix (+ (/ (* oran distance) SAYI) 0.5)) SAYI))
        //
        // МАТЕМАТИКА:
        //   1. Делим значение на SAYI (10)
        //   2. Добавляем 0.5 (для правильного округления)
        //   3. Берем целую часть (Floor)
        //   4. Умножаем обратно на SAYI
        //
        // ПРИМЕРЫ:
        //   Round(1234) = 1230 (округляется вниз)
        //   Round(1256) = 1260 (округляется вверх)
        //   Round(1250) = 1250 (уже кратно 10)
        //
        // ПАРАМЕТРЫ:
        //   value - значение для округления (в миллиметрах)
        //
        // ВОЗВРАЩАЕТ:
        //   Округленное значение (кратное 10 мм)
        private static double Round(double value)
        {
            // Math.Floor - округляет вниз до ближайшего целого числа
            // value / SAYI + 0.5 - делим на 10 и добавляем 0.5 для правильного округления
            // * SAYI - умножаем обратно на 10
            return Math.Floor(value / SAYI + 0.5) * SAYI;
        }

        // ====================================================================================
        // ФУНКЦИЯ: Is90 (Проверка на 90 градусов)
        // ====================================================================================
        // НАЗНАЧЕНИЕ: Проверяет, равен ли угол 90 градусам (с допуском)
        //
        // ЗАЧЕМ НУЖЕН ДОПУСК:
        //   В чертежах углы могут быть неточными (89.5° или 90.3° вместо 90°)
        //   Поэтому мы проверяем не точно 90°, а в диапазоне 85° - 95°
        //
        // ПАРАМЕТРЫ:
        //   angleDeg - угол в градусах
        //
        // ВОЗВРАЩАЕТ:
        //   true - если угол примерно 90° (85° - 95°)
        //   false - если угол сильно отличается от 90°
        private static bool Is90(double angleDeg)
        {
            // Math.Abs - абсолютное значение (убирает знак минус)
            // Проверяем, что разница между углом и 90° меньше 5°
            return Math.Abs(angleDeg - 90.0) < 5.0;
        }

        // ====================================================================================
        // СВЯЗЬ ПОЗИЦИИ С ПОЛИЛИНИЕЙ ("Determination" помнит, откуда взялись значения)
        // ====================================================================================
        // Кнопка "Determination" распознаёт форму по полилинии один раз. Чтобы значения
        // A-F/TIP/BOY автоматически обновлялись позже (если пользователь изменит длину/угол
        // той же полилинии), ссылка на неё (handle) сохраняется в блоке RL-POS через XDATA -
        // переживает сохранение и переоткрытие чертежа. Дальше:
        //   - REGEN/REGENALL пересинхронизируют ВСЕ связанные позиции в чертеже (см. ExtensionApp.cs)
        //   - TDDBN пересинхронизирует только те позиции, которые выбраны для расчёта длины
        // При следующем открытии EEN окно просто читает уже обновлённые атрибуты блока - никакой
        // отдельной логики в PoseEditWindow для этого не нужно.
        private const string LinkAppName = "POSEDIT_LINK";

        private static void EnsureRegApp(Database db, Transaction tr)
        {
            RegAppTable regTable = tr.GetObject(db.RegAppTableId, OpenMode.ForRead) as RegAppTable;
            if (regTable.Has(LinkAppName)) return;

            regTable.UpgradeOpen();
            RegAppTableRecord app = new RegAppTableRecord { Name = LinkAppName };
            regTable.Add(app);
            tr.AddNewlyCreatedDBObject(app, true);
        }

        // Запоминает, что позиция blockId распознана по геометрии polylineId
        public static void SetLinkedPolyline(ObjectId blockId, ObjectId polylineId)
        {
            if (blockId.IsNull || polylineId.IsNull) return;
            Database db = blockId.Database;

            using (Transaction tr = db.TransactionManager.StartTransaction())
            {
                EnsureRegApp(db, tr);

                BlockReference blkRef = tr.GetObject(blockId, OpenMode.ForWrite) as BlockReference;
                Entity line = tr.GetObject(polylineId, OpenMode.ForRead) as Entity;
                if (blkRef == null || line == null) { tr.Commit(); return; }

                using (ResultBuffer rb = new ResultBuffer(
                    new TypedValue((int)DxfCode.ExtendedDataRegAppName, LinkAppName),
                    new TypedValue((int)DxfCode.ExtendedDataAsciiString, line.Handle.ToString())))
                {
                    blkRef.XData = rb;
                }

                tr.Commit();
            }
        }

        // Читает сохранённый handle связанной полилинии и превращает его в ObjectId
        // (ObjectId.Null, если связи нет или объект больше не существует)
        private static ObjectId GetLinkedPolylineId(Transaction tr, ObjectId blockId)
        {
            BlockReference blkRef = tr.GetObject(blockId, OpenMode.ForRead) as BlockReference;
            if (blkRef == null) return ObjectId.Null;

            ResultBuffer rb = blkRef.GetXDataForApplication(LinkAppName);
            if (rb == null) return ObjectId.Null;

            foreach (TypedValue tv in rb.AsArray())
            {
                if (tv.TypeCode != (int)DxfCode.ExtendedDataAsciiString) continue;

                string handleStr = tv.Value as string;
                if (string.IsNullOrEmpty(handleStr)) continue;
                if (!long.TryParse(handleStr, System.Globalization.NumberStyles.HexNumber, null, out long handleVal)) continue;

                try
                {
                    ObjectId id = blockId.Database.GetObjectId(false, new Handle(handleVal), 0);
                    if (!id.IsErased) return id;
                }
                catch { /* handle не найден в базе - связь протухла, игнорируем */ }
            }
            return ObjectId.Null;
        }

        // Пересчитывает TIP/A-F/R/BOY для одной позиции по связанной полилинии (аналог
        // повторного нажатия "Determination", но без диалога и без выбора мышью).
        // Возвращает true, если реально что-то пересчитала (связь есть, объект найден, форма распознана).
        public static bool SyncFromLinkedPolyline(ObjectId blockId)
        {
            if (blockId.IsNull || !blockId.IsValid || blockId.IsErased) return false;

            ObjectId lineId;
            using (Transaction tr = blockId.Database.TransactionManager.StartTransaction())
            {
                lineId = GetLinkedPolylineId(tr, blockId);
                tr.Commit();
            }
            if (lineId.IsNull || !lineId.IsValid || lineId.IsErased) return false;

            RebarResult result = Recognize(lineId);
            if (result.Type == "99") return false;

            BlockHelper.SetAttributes(blockId, new Dictionary<string, string>
            {
                ["TIP"] = result.Type,
                ["A"] = result.A,
                ["B"] = result.B,
                ["C"] = result.C,
                ["D"] = result.D,
                ["E"] = result.E,
                ["F"] = result.F,
                ["R"] = result.R,
                ["BOY"] = result.Length,
            });

            // Без этого BOY остаётся невидимым/на старом месте и может наложиться на TB -
            // именно эта функция решает, показывать ли BOY и где его разместить рядом с TB.
            PozHelper.RepositionShapeText(blockId);
            return true;
        }

        // Проходит по всем блокам RL-POS в текущем пространстве чертежа и пересинхронизирует
        // те из них, у кого есть связанная полилиния. Используется по REGEN/REGENALL (см. ExtensionApp.cs).
        public static int SyncAllLinkedBlocksInDatabase(Database db)
        {
            int synced = 0;
            var ids = new List<ObjectId>();

            using (Transaction tr = db.TransactionManager.StartTransaction())
            {
                BlockTable bt = tr.GetObject(db.BlockTableId, OpenMode.ForRead) as BlockTable;
                BlockTableRecord ms = tr.GetObject(bt[BlockTableRecord.ModelSpace], OpenMode.ForRead) as BlockTableRecord;
                foreach (ObjectId id in ms)
                {
                    BlockReference blkRef = tr.GetObject(id, OpenMode.ForRead) as BlockReference;
                    if (blkRef != null && blkRef.Name == "RL-POS") ids.Add(id);
                }
                tr.Commit();
            }

            foreach (ObjectId id in ids)
            {
                if (SyncFromLinkedPolyline(id)) synced++;
            }
            return synced;
        }
    }
